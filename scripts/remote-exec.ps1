<#
.SYNOPSIS
    Drive a paired OYM device from this harness, without clicking the REMOTE tab.

.DESCRIPTION
    Talks to the running DEV app over its WebView2 debugging port (CDP) and calls
    the same Tauri commands the REMOTE page calls. That bridge is debug-only, so
    nothing here works against a REL app — see docs/AGENTS-REFERENCE.md.

    The device side must run a link build that understands the `shell` profile and
    have OYM_TEST_SHELL=1 in its environment. See docs/remote-servicing/TEST-SHELL.md.

    PTY output is captured inside the page (window.__oymRemote) so it survives
    between calls; `read` drains it.

.EXAMPLE
    ./scripts/remote-exec.ps1 devices

.EXAMPLE
    ./scripts/remote-exec.ps1 start dev_bd2ab9967b930772
    ./scripts/remote-exec.ps1 send  dev_bd2ab9967b930772 "Get-Content C:\ProgramData\OYM\Link\service-child.log -Tail 20"
    ./scripts/remote-exec.ps1 read  dev_bd2ab9967b930772
    ./scripts/remote-exec.ps1 stop  dev_bd2ab9967b930772

.EXAMPLE
    # Run one command and wait for its marker, one call:
    ./scripts/remote-exec.ps1 wait dev_bd2ab9967b930772 -Text 'echo DONE_MARK' -Match 'DONE_MARK'
#>
param(
    [Parameter(Mandatory = $true, Position = 0)]
    [ValidateSet('devices', 'listen', 'start', 'send', 'read', 'stop', 'wait', 'reset')]
    [string]$Action,

    [Parameter(Position = 1)]
    [string]$Device,

    [Parameter(Position = 2)]
    [string]$Text,

    [string]$Profile = 'shell',
    [string]$Match,
    [int]$TimeoutSeconds = 30,
    # Not `$Raw`: PowerShell variable names are case-insensitive, so a local
    # `$raw` of type string would collide with this switch and fail to bind.
    [switch]$NoEnter,
    [int]$Port = 9222
)

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$probe = Join-Path $repo 'scripts/ui-probe.mjs'
if (-not (Test-Path $probe)) { throw "missing $probe" }

function Invoke-Js {
    param([string]$Expression)
    $out = node $probe --port $Port $Expression 2>&1
    if ($LASTEXITCODE -ne 0) { throw "page evaluation failed: $out" }
    return ($out | Out-String)
}

# Device ids are generated by the gateway as dev_<hex>; interpolating anything
# else into the page expression would be a script-injection hole.
function Assert-Device {
    if (-not $Device) { throw "-Device is required for '$Action'" }
    if ($Device -notmatch '^dev_[0-9a-f]{8,}$') { throw "not a device id: $Device" }
}

function Convert-Ansi {
    param([string]$Value)
    # Strip CSI/OSC sequences and carriage returns so output reads as plain text.
    $clean = $Value -replace "`e\[[0-9;?]*[a-zA-Z]", ''
    $clean = $clean -replace "`e\][^\a]*\a", ''
    return ($clean -replace "`r", '')
}

$listenTemplate = @'
(async () => {
  const w = window;
  const id = "<DEVICE>";
  w.__oymRemote = w.__oymRemote || { buf: {}, hooked: {} };
  if (!w.__oymRemote.hooked[id]) {
    w.__oymRemote.buf[id] = w.__oymRemote.buf[id] || [];
    await w.__TAURI__.event.listen("remote-event", (event) => {
      const p = event && event.payload;
      if (!p || p.deviceId !== id) return;
      if (p.type === "session_data" && p.data) {
        const binary = atob(p.data);
        const bytes = Uint8Array.from(binary, (c) => c.charCodeAt(0));
        const text = new TextDecoder().decode(bytes);
        w.__oymRemote.buf[id].push(text);
        // Answer a cursor-position request (DSR, ESC[6n). The device PTY is not a
        // real terminal: PowerShell's console host blocks on this reply before it
        // paints a prompt, so a headless reader must answer or the session hangs
        // with no output at all. xterm.js in the UI answers it for a human.
        if (text.indexOf("\u001b[6n") >= 0) {
          w.__TAURI__.core.invoke("remote_session_input", { deviceId: id, data: btoa("\u001b[1;1R") })
            .catch(() => {});
        }
      } else if (p.type === "session_ready" || p.type === "session_exit") {
        const detail = (p.pid != null ? " pid " + p.pid : "") + (p.integrity ? " integrity " + p.integrity : "");
        w.__oymRemote.buf[id].push("\n[" + p.type + detail + (p.code != null ? " code " + p.code : "") + "]\n");
      }
    });
    w.__oymRemote.hooked[id] = true;
  }
  return "listening " + id;
})()
'@

$readTemplate = @'
(() => {
  const w = window;
  const id = "<DEVICE>";
  if (!w.__oymRemote || !w.__oymRemote.buf[id]) return "";
  const pending = w.__oymRemote.buf[id];
  w.__oymRemote.buf[id] = [];
  return pending.join("");
})()
'@

switch ($Action) {
    'devices' {
        $expr = @'
(async () => {
  const list = await window.__TAURI__.core.invoke("remote_devices_list");
  return JSON.stringify(list.map((d) => ({
    id: d.id, name: d.name, online: d.online, integrity: d.integrity,
    session: d.sessionState, profile: d.sessionProfile
  })));
})()
'@
        $json = Invoke-Js $expr
        $devices = $json | ConvertFrom-Json
        $devices | Format-Table -AutoSize | Out-String -Width 200
        break
    }

    'listen' {
        Assert-Device
        Invoke-Js ($listenTemplate.Replace('<DEVICE>', $Device)) | Out-Null
        break
    }

    'start' {
        Assert-Device
        if ($Profile -notmatch '^(shell|pi-maintenance)$') { throw "unsupported profile: $Profile" }
        # Capture before the session opens, or the first scrollback is lost.
        Invoke-Js ($listenTemplate.Replace('<DEVICE>', $Device)) | Out-Null
        $expr = @'
(async () => {
  const opened = await window.__TAURI__.core.invoke("remote_session_start", {
    deviceId: "<DEVICE>", cols: 140, rows: 40, profile: "<PROFILE>"
  });
  return JSON.stringify({ profile: opened.profile, routes: opened.routes.length });
})()
'@
        $result = Invoke-Js ($expr.Replace('<DEVICE>', $Device).Replace('<PROFILE>', $Profile))
        "started: $($result.Trim())"
        Start-Sleep -Milliseconds 1200
        break
    }

    'send' {
        Assert-Device
        if ($null -eq $Text) { throw "-Text is required for 'send'" }
        $payload = if ($NoEnter) { $Text } else { "`r" + $Text + "`r" }
        $b64 = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($payload))
        $expr = @'
(async () => {
  await window.__TAURI__.core.invoke("remote_session_input", { deviceId: "<DEVICE>", data: "<B64>" });
  return "sent";
})()
'@
        Invoke-Js ($expr.Replace('<DEVICE>', $Device).Replace('<B64>', $b64)) | Out-Null
        break
    }

    'read' {
        Assert-Device
        $captured = Invoke-Js ($readTemplate.Replace('<DEVICE>', $Device))
        Convert-Ansi $captured
        break
    }

    'stop' {
        Assert-Device
        $expr = @'
(async () => {
  const result = await window.__TAURI__.core.invoke("remote_session_terminate", { deviceId: "<DEVICE>" });
  return JSON.stringify(result);
})()
'@
        Invoke-Js ($expr.Replace('<DEVICE>', $Device))
        break
    }

    'reset' {
        Assert-Device
        # A half-typed line or an unterminated quote leaves PowerShell in a
        # continuation prompt (`>>`), where every later command is swallowed as
        # more input instead of being executed. Ctrl+C aborts the current line;
        # the extra Enter clears whatever is left.
        $expr = @'
(async () => {
  await window.__TAURI__.core.invoke("remote_session_input", { deviceId: "<DEVICE>", data: btoa(String.fromCharCode(3)) });
  await window.__TAURI__.core.invoke("remote_session_input", { deviceId: "<DEVICE>", data: btoa("\r") });
  return "reset";
})()
'@
        Invoke-Js ($expr.Replace('<DEVICE>', $Device)) | Out-Null
        Start-Sleep -Milliseconds 600
        break
    }

    'wait' {
        Assert-Device
        if ($null -eq $Text) { throw "-Text is required for 'wait'" }
        if (-not $Match) { throw "-Match is required for 'wait'" }
        Invoke-Js ($listenTemplate.Replace('<DEVICE>', $Device)) | Out-Null
        # The leading CR is not cosmetic: the first keystroke after `session_ready`
        # can be consumed while the console is still settling its input buffer, and
        # an empty line is a no-op at a shell prompt.
        $payload = "`r" + $Text + "`r"
        $b64 = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($payload))
        $sendExpr = @'
(async () => {
  await window.__TAURI__.core.invoke("remote_session_input", { deviceId: "<DEVICE>", data: "<B64>" });
  return "sent";
})()
'@
        Invoke-Js ($sendExpr.Replace('<DEVICE>', $Device).Replace('<B64>', $b64)) | Out-Null

        $seen = ''
        $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
        while ((Get-Date) -lt $deadline) {
            Start-Sleep -Milliseconds 400
            $seen += Convert-Ansi (Invoke-Js ($readTemplate.Replace('<DEVICE>', $Device)))
            if ($seen -match [regex]::Escape($Match)) { break }
        }
        $seen
        if ($seen -notmatch [regex]::Escape($Match)) {
            throw "timed out after ${TimeoutSeconds}s waiting for '$Match'"
        }
        break
    }
}
